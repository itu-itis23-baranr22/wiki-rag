let current = "en";

export function detectLanguage() {
  let saved = null;
  try {
    saved = localStorage.getItem("wiki-rag-lang");
  } catch {
    /* storage can be blocked; the browser language still works */
  }
  if (saved && STRINGS[saved]) return saved;
  return (navigator.language || "en").toLowerCase().startsWith("tr") ? "tr" : "en";
}

export function setLanguage(language) {
  current = STRINGS[language] ? language : "en";
  document.documentElement.lang = current;
  try {
    localStorage.setItem("wiki-rag-lang", current);
  } catch {
    /* the choice just won't survive a reload */
  }
}

export const language = () => current;

export function t(key, vars = {}) {
  const template = STRINGS[current][key] ?? STRINGS.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => (name in vars ? vars[name] : `{${name}}`));
}

export const formatNumber = (value) => new Intl.NumberFormat(current).format(value);

export const formatPercent = (value) =>
  value === null || value === undefined
    ? t("na")
    : new Intl.NumberFormat(current, { style: "percent", maximumFractionDigits: 0 }).format(value);

export function formatDuration(ms) {
  const seconds = ms / 1000;
  if (ms < 1000) return current === "tr" ? `${Math.round(ms)} ms` : `${Math.round(ms)} ms`;
  const text = new Intl.NumberFormat(current, { maximumFractionDigits: seconds < 10 ? 1 : 0 }).format(seconds);
  return current === "tr" ? `${text} sn` : `${text} s`;
}

export function countOf(value, enSingular, enPlural, trWord) {
  const number = formatNumber(value);
  if (current === "tr") return `${number} ${trWord}`;
  return `${number} ${value === 1 ? enSingular : enPlural}`;
}

